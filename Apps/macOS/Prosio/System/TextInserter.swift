import AppKit
@preconcurrency import ApplicationServices
import ProsioCore

/// Clipboard + Cmd+V insertion with AX fallback. Owned by mac-system agent.
final class TextInserter: TextInserting {
    private let settings: AppSettings

    /// Pasteboard types clipboard managers (Copied, Paste, Raycast, ...) recognize to skip
    /// recording an item — see https://nspasteboard.org.
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// How long to wait before restoring the user's original clipboard after a synthetic Cmd+V.
    /// A native AppKit/UIKit text field reads the pasteboard synchronously within the paste event,
    /// so this could be much shorter for them — but Electron/web-based apps (Slack, Notion,
    /// Chrome-based editors) read it asynchronously through their own event loop, and restoring
    /// too early races them: they end up pasting whatever we restore the clipboard to instead of
    /// our text. 750ms is a trade-off between that failure mode and the (harmless) window where
    /// the user's *previous* clipboard item is briefly unavailable.
    private static let clipboardRestoreDelayNanoseconds: UInt64 = 750_000_000

    init(settings: AppSettings) {
        self.settings = settings
    }

    func insert(_ text: String, into context: FocusContext?) async -> InsertionOutcome {
        if context?.isSecureInput == true {
            ProsioLog.textInsertion.info("copiedToClipboard: secure input field focused")
            Self.writePlain(text)
            return .copiedToClipboard
        }

        guard AXIsProcessTrusted() else {
            // Without Accessibility trust we can neither post a synthetic Cmd+V reliably nor use
            // the AX fallback; leave the text on the clipboard for the user to paste themselves.
            ProsioLog.textInsertion.info("copiedToClipboard: Accessibility not trusted")
            Self.writePlain(text)
            return .copiedToClipboard
        }

        let pasteboard = NSPasteboard.general
        let snapshot = Self.snapshot(of: pasteboard)

        Self.writeTransient(text, to: pasteboard)
        let ourChangeCount = pasteboard.changeCount

        if Self.postCmdV() {
            ProsioLog.textInsertion.info("pasted: posted synthetic Cmd+V")
            if settings.restoreClipboard {
                Task {
                    try? await Task.sleep(nanoseconds: Self.clipboardRestoreDelayNanoseconds)
                    if pasteboard.changeCount == ourChangeCount {
                        Self.restore(snapshot, to: pasteboard)
                    }
                }
            }
            return .pasted
        }

        // Posting failed; try setting the selected text directly via Accessibility.
        if Self.setSelectedTextViaAX(text) {
            ProsioLog.textInsertion.info("accessibility: Cmd+V post failed, AX selected-text fallback succeeded")
            if settings.restoreClipboard {
                Self.restore(snapshot, to: pasteboard)
            }
            return .accessibility
        }

        // Both paths failed: make sure the plain text (no transient markers) is what's left on
        // the clipboard, since that's now the user's only way to get it.
        ProsioLog.textInsertion.info("copiedToClipboard: Cmd+V post and AX fallback both failed")
        Self.writePlain(text)
        return .copiedToClipboard
    }

    // MARK: - Pasteboard helpers

    private static func writePlain(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    private static func writeTransient(_ text: String, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setString("true", forType: transientType)
        item.setString("true", forType: autoGeneratedType)
        pasteboard.writeObjects([item])
    }

    private static func snapshot(of pasteboard: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        guard let items = pasteboard.pasteboardItems else { return [] }
        return items.map { item in
            var dict: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) {
                    dict[type] = data
                }
            }
            return dict
        }
    }

    private static func restore(_ snapshot: [[NSPasteboard.PasteboardType: Data]], to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !snapshot.isEmpty else { return }
        let items = snapshot.map { dict -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in dict {
                item.setData(data, forType: type)
            }
            return item
        }
        pasteboard.writeObjects(items)
    }

    // MARK: - Cmd+V synthesis

    private static func postCmdV() -> Bool {
        guard let source = CGEventSource(stateID: .combinedSessionState) else { return false }
        guard let keyDown = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: false) else {
            return false
        }
        keyDown.flags = .maskCommand
        keyUp.flags = .maskCommand
        keyDown.post(tap: .cgSessionEventTap)
        keyUp.post(tap: .cgSessionEventTap)
        return true
    }

    // MARK: - AX fallback

    private static func setSelectedTextViaAX(_ text: String) -> Bool {
        let systemWide = AXUIElementCreateSystemWide()
        var focusedRef: AnyObject?
        guard AXUIElementCopyAttributeValue(systemWide, kAXFocusedUIElementAttribute as CFString, &focusedRef) == .success,
              let focusedRef, CFGetTypeID(focusedRef) == AXUIElementGetTypeID() else {
            return false
        }
        let element = unsafeDowncast(focusedRef, to: AXUIElement.self)
        let result = AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString, text as CFTypeRef)
        return result == .success
    }
}
